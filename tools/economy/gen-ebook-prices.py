#!/usr/bin/env python3
"""Writes functions/_lib/economy/ebook_prices.js from the bundled ebook
catalogue (flutter_app/assets/content/books.json) so checkout never trusts
the phone's ebook price. Re-run after books.json changes."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
books = json.loads((root / 'flutter_app/assets/content/books.json').read_text())
prices = {}
for it in books.get('items', []):
    title = str(it.get('title') or '').strip()
    price = it.get('price')
    if not title or not isinstance(price, (int, float)):
        continue
    prices['ebook:' + title.lower()] = int(price)
out = root / 'functions/_lib/economy/ebook_prices.js'
out.write_text(
    '/* Generated by tools/economy/gen-ebook-prices.py from books.json. Do not edit. */\n'
    'export const BUNDLED_EBOOK_PRICES = ' + json.dumps(prices, indent=2) + ';\n'
)
print(len(prices), 'ebook prices ->', out)
